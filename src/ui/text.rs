pub fn tx() -> &'static Texts {
    match lang::current() {
        Lang::Zh => &ZH,
        Lang::En => &EN,
    }
}

/// 三选一界面的刷新按钮文字
pub fn orb_refresh_label(remaining: u32, cost: u32) -> String {
    match (lang::current(), remaining, cost) {
        (Lang::Zh, 0, _) => "刷新次数已用完".into(),
        (Lang::Zh, n, 0) => format!("刷新选项（免费，剩 {n} 次）"),
        (Lang::Zh, n, c) => format!("刷新选项（{c} 卢恩，剩 {n} 次）"),
        (Lang::En, 0, _) => "No Rerolls Left".into(),
        (Lang::En, n, 0) => format!("Reroll Options (Free, {n} left)"),
        (Lang::En, n, c) => format!("Reroll Options ({c} Runes, {n} left)"),
    }
}

